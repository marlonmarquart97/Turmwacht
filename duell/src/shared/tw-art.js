const OL='#120b05';
function P(g,pts){g.beginPath();pts.forEach((p,i)=>i?g.lineTo(p[0],p[1]):g.moveTo(p[0],p[1]));g.closePath();}
function E(g,x,y,rx,ry){g.beginPath();g.ellipse(x,y,rx,ry==null?rx:ry,0,0,Math.PI*2);}
function F(g,fill,lw=1.6,st=OL){g.fillStyle=fill;g.fill();if(lw){g.lineWidth=lw;g.strokeStyle=st;g.lineJoin='round';g.stroke();}}
function LG(g,x0,y0,x1,y1,...c){const r=g.createLinearGradient(x0,y0,x1,y1);c.forEach((k,i)=>r.addColorStop(i/(c.length-1),k));return r;}
function L(g,x1,y1,x2,y2,col,w){g.beginPath();g.moveTo(x1,y1);g.lineTo(x2,y2);g.strokeStyle=col;g.lineWidth=w;g.lineCap='round';g.stroke();}
